//! SDK emission, and the corpus that keeps its tests honest.
//!
//! ## The tautology problem, and the way out
//!
//! Generated tests are usually worthless. If a generator emits both the
//! constants and the test that checks them, the test asserts that the generator
//! did what the generator did — it passes by construction and detects nothing.
//! Emitting one per language would multiply that by the number of languages and
//! call the result "full coverage".
//!
//! The way out is a **shared conformance corpus**: one JSON document, emitted
//! from the Rust reference implementation, containing the resolved values every
//! language must agree with. Each language's generated test loads *that* and
//! compares its own constants against it. Now a per-language emitter bug is
//! detectable, because the corpus and the language constants travel through
//! different code paths — the corpus is serialised from `Theme`, while the
//! constants are formatted by a per-language emitter.
//!
//! What this does and does not prove, stated plainly:
//!
//! - It **does** prove every language's constants agree with the Rust
//!   reference, which is the property that matters: an SDK that disagrees with
//!   the source paints the wrong colour.
//! - It does **not** prove the Rust reference is correct. That is what
//!   `pente-spec`'s own tests are for, and they pin against the bytes the fleet
//!   already ships.
//! - It does **not** prove the emitted code is idiomatic, or that it compiles
//!   under every toolchain version. Compilation is checked for Rust (by
//!   `include!`) and is a CI matter for the rest — recorded as a limit rather
//!   than claimed as covered.

use std::fmt::Write as _;

use pente_spec::{FleetTheme, Srgb8, Theme};

use crate::{ramp_slots, roles_named, ANSI_NAMES};

/// A language the theme is published to.
///
/// Closed, and `ALL` drives both emission and the conformance matrix, so adding
/// a language without teaching it to render every theme is a compile error.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Lang {
    TypeScript,
    Python,
    Go,
}

impl Lang {
    pub const ALL: [Self; 3] = [Self::TypeScript, Self::Python, Self::Go];

    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::TypeScript => "typescript",
            Self::Python => "python",
            Self::Go => "go",
        }
    }

    /// The SDK module for one theme.
    #[must_use]
    pub fn module_name(self, theme: FleetTheme) -> String {
        let slug = theme.slug();
        match self {
            Self::TypeScript => format!("{slug}.ts"),
            Self::Python => format!("{slug}.py"),
            Self::Go => format!("{slug}.go"),
        }
    }

    /// The generated conformance test — ONE per language, not per theme: it
    /// iterates the corpus, so a new theme is covered without a new test file.
    #[must_use]
    pub const fn test_name(self) -> &'static str {
        match self {
            Self::TypeScript => "conformance.test.ts",
            Self::Python => "test_conformance.py",
            Self::Go => "conformance_test.go",
        }
    }

    /// Emit the SDK module for one theme.
    #[must_use]
    pub fn render_module(self, theme: FleetTheme, t: &Theme) -> String {
        match self {
            Self::TypeScript => ts_module(theme, t),
            Self::Python => py_module(theme, t),
            Self::Go => go_module(theme, t),
        }
    }

    /// Emit this language's conformance test.
    #[must_use]
    pub fn render_test(self) -> String {
        match self {
            Self::TypeScript => ts_test(),
            Self::Python => py_test(),
            Self::Go => go_test(),
        }
    }

    /// The module scaffolding a real toolchain needs to build and test this SDK.
    ///
    /// Generated rather than committed by hand for the same reason as
    /// everything else: without it the emitted tests are unrunnable, and an
    /// unrunnable test is indistinguishable from a passing one until someone
    /// tries. `go test` needs a `go.mod`; `vitest` needs a `package.json`;
    /// `pytest` needs the package importable from its own directory.
    #[must_use]
    pub fn scaffold(self) -> Vec<(&'static str, String)> {
        match self {
            Self::Go => vec![(
                "go.mod",
                "// Generated by pente-forge — DO NOT EDIT\n\
                 module github.com/pleme-io/pente/sdk/go\n\n\
                 go 1.21\n"
                    .to_string(),
            )],
            Self::TypeScript => vec![
                (
                    "package.json",
                    "{\n  \"name\": \"@pleme-io/pente\",\n  \"version\": \"0.1.0\",\n  \
                     \"description\": \"Generated by pente-forge — DO NOT EDIT\",\n  \
                     \"type\": \"module\",\n  \"scripts\": { \"test\": \"vitest run\" },\n  \
                     \"devDependencies\": { \"vitest\": \"^2\", \"typescript\": \"^5\" }\n}\n"
                        .to_string(),
                ),
                (
                    "tsconfig.json",
                    "{\n  \"compilerOptions\": {\n    \"target\": \"ES2022\",\n    \
                     \"module\": \"ESNext\",\n    \"moduleResolution\": \"bundler\",\n    \
                     \"strict\": true,\n    \"noEmit\": true,\n    \
                     \"resolveJsonModule\": true,\n    \"types\": [\"vitest/globals\"]\n  },\n  \
                     \"include\": [\"*.ts\"]\n}\n"
                        .to_string(),
                ),
            ],
            Self::Python => vec![(
                "conftest.py",
                "# Generated by pente-forge — DO NOT EDIT\n\
                 #\n\
                 # Puts this directory on sys.path so the generated theme modules import\n\
                 # by bare name, which is what the conformance test does.\n\
                 import pathlib\n\
                 import sys\n\n\
                 sys.path.insert(0, str(pathlib.Path(__file__).parent))\n"
                    .to_string(),
            )],
        }
    }
}

// ── The corpus ─────────────────────────────────────────────────────────────

/// The canonical conformance corpus: every theme, every resolved value, as
/// JSON.
///
/// Serialised by hand through a typed writer rather than a JSON library, for
/// the same reason the Nix emitter has an AST: this is the one artifact every
/// language's test is judged against, so its escaping and ordering live in one
/// reviewable place. The inputs are hex strings and identifiers, so the escape
/// surface is small — but it is written out rather than assumed.
#[must_use]
pub fn corpus() -> String {
    let mut out = String::new();
    out.push_str("{\n  \"themes\": {\n");
    for (ti, theme) in FleetTheme::ALL.iter().enumerate() {
        let t = theme.load().expect("authored theme compiles");
        let _ = write!(out, "    \"{}\": {{\n", theme.slug());

        let _ = write!(out, "      \"ramp\": {{");
        for (i, (name, c)) in ramp_slots(&t).into_iter().enumerate() {
            let sep = if i == 0 { "\n" } else { ",\n" };
            let _ = write!(out, "{sep}        \"{name}\": \"{}\"", c.to_bare_hex());
        }
        out.push_str("\n      },\n");

        let _ = write!(out, "      \"ansi\": [");
        for (i, tok) in t.ansi.in_order().into_iter().enumerate() {
            let sep = if i == 0 { "\n" } else { ",\n" };
            let _ = write!(
                out,
                "{sep}        {{ \"name\": \"{}\", \"hex\": \"{}\" }}",
                ANSI_NAMES[i],
                t.resolve(tok).to_bare_hex()
            );
        }
        out.push_str("\n      ],\n");

        let _ = write!(out, "      \"roles\": {{");
        for (i, (name, tok)) in roles_named(&t).into_iter().enumerate() {
            let sep = if i == 0 { "\n" } else { ",\n" };
            let _ = write!(
                out,
                "{sep}        \"{name}\": \"{}\"",
                t.resolve(tok).to_bare_hex()
            );
        }
        out.push_str("\n      }\n");

        let tail = if ti + 1 == FleetTheme::ALL.len() { "\n" } else { ",\n" };
        let _ = write!(out, "    }}{tail}");
    }
    out.push_str("  }\n}\n");
    out
}

// ── Emitters ───────────────────────────────────────────────────────────────

fn banner(theme: FleetTheme, lang: &str, comment: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "{comment} Generated by pente-forge ({lang}) — DO NOT EDIT");
    let _ = writeln!(
        s,
        "{comment} Source of truth: pente/themes/{}.theme.lisp",
        theme.slug()
    );
    let _ = writeln!(s, "{comment} Verify: pente-forge check   (fails on any drift)");
    s
}

fn hex(c: Srgb8) -> String {
    format!("#{}", c.to_bare_hex())
}

fn ts_module(theme: FleetTheme, t: &Theme) -> String {
    let mut s = banner(theme, "typescript", "//");
    let _ = writeln!(s, "\nexport const RAMP = {{");
    for (name, c) in ramp_slots(t) {
        let _ = writeln!(s, "  {name}: \"{}\",", hex(c));
    }
    let _ = writeln!(s, "}} as const;\n");
    let _ = writeln!(s, "export const ANSI: readonly string[] = [");
    for tok in t.ansi.in_order() {
        let _ = writeln!(s, "  \"{}\",", hex(t.resolve(tok)));
    }
    let _ = writeln!(s, "];\n");
    let _ = writeln!(s, "export const ROLES = {{");
    for (name, tok) in roles_named(t) {
        let _ = writeln!(s, "  \"{name}\": \"{}\",", hex(t.resolve(tok)));
    }
    let _ = writeln!(s, "}} as const;\n");
    let _ = writeln!(s, "export const NAME = \"{}\";", theme.slug());
    s
}

fn py_module(theme: FleetTheme, t: &Theme) -> String {
    let mut s = banner(theme, "python", "#");
    let _ = writeln!(s, "\nRAMP = {{");
    for (name, c) in ramp_slots(t) {
        let _ = writeln!(s, "    \"{name}\": \"{}\",", hex(c));
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "ANSI = [");
    for tok in t.ansi.in_order() {
        let _ = writeln!(s, "    \"{}\",", hex(t.resolve(tok)));
    }
    let _ = writeln!(s, "]\n");
    let _ = writeln!(s, "ROLES = {{");
    for (name, tok) in roles_named(t) {
        let _ = writeln!(s, "    \"{name}\": \"{}\",", hex(t.resolve(tok)));
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "NAME = \"{}\"", theme.slug());
    s
}

fn go_module(theme: FleetTheme, t: &Theme) -> String {
    let mut s = banner(theme, "go", "//");
    let _ = writeln!(s, "\npackage pente\n");
    let ident = theme.slug().to_string();
    let cap = {
        let mut c = ident.chars();
        c.next().map_or_else(String::new, |f| f.to_uppercase().collect::<String>() + c.as_str())
    };
    let _ = writeln!(s, "var Ramp{cap} = map[string]string{{");
    for (name, c) in ramp_slots(t) {
        let _ = writeln!(s, "\t\"{name}\": \"{}\",", hex(c));
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "var Ansi{cap} = []string{{");
    for tok in t.ansi.in_order() {
        let _ = writeln!(s, "\t\"{}\",", hex(t.resolve(tok)));
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "var Roles{cap} = map[string]string{{");
    for (name, tok) in roles_named(t) {
        let _ = writeln!(s, "\t\"{name}\": \"{}\",", hex(t.resolve(tok)));
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "const Name{cap} = \"{}\"", theme.slug());
    s
}

// ── Conformance tests ──────────────────────────────────────────────────────
//
// Each loads corpus.json — emitted from the Rust reference — and compares this
// language's constants against it. The two travel through different code paths,
// so a per-language emitter bug is detectable rather than self-confirming.

fn ts_test() -> String {
    let mut s = String::from(
        "// Generated by pente-forge (typescript conformance) — DO NOT EDIT\n\
         //\n\
         // Compares this language's constants against corpus.json, which is emitted\n\
         // from the Rust reference. The two travel through different code paths, so a\n\
         // TypeScript emitter bug is detectable rather than self-confirming.\n\n",
    );
    s.push_str("import { describe, it, expect } from \"vitest\";\n");
    s.push_str("import corpus from \"./corpus.json\";\n");
    for theme in FleetTheme::ALL {
        let _ = writeln!(
            s,
            "import * as {} from \"./{}\";",
            theme.slug(),
            theme.slug()
        );
    }
    s.push_str("\nconst MODULES: Record<string, any> = { ");
    for theme in FleetTheme::ALL {
        let _ = write!(s, "{}, ", theme.slug());
    }
    s.push_str("};\n\n");
    s.push_str(
        "describe(\"pente conformance\", () => {\n\
         \x20 for (const [name, expected] of Object.entries<any>(corpus.themes)) {\n\
         \x20   const mod = MODULES[name];\n\
         \x20   it(`${name} exists`, () => { expect(mod).toBeDefined(); });\n\
         \x20   it(`${name} ramp matches the corpus`, () => {\n\
         \x20     for (const [slot, hex] of Object.entries<string>(expected.ramp)) {\n\
         \x20       expect(mod.RAMP[slot]).toBe(`#${hex}`);\n\
         \x20     }\n\
         \x20     expect(Object.keys(mod.RAMP).length).toBe(16);\n\
         \x20   });\n\
         \x20   it(`${name} ansi matches the corpus`, () => {\n\
         \x20     expect(mod.ANSI.length).toBe(16);\n\
         \x20     expected.ansi.forEach((e: any, i: number) => {\n\
         \x20       expect(mod.ANSI[i]).toBe(`#${e.hex}`);\n\
         \x20     });\n\
         \x20   });\n\
         \x20   it(`${name} roles match the corpus`, () => {\n\
         \x20     for (const [role, hex] of Object.entries<string>(expected.roles)) {\n\
         \x20       expect(mod.ROLES[role]).toBe(`#${hex}`);\n\
         \x20     }\n\
         \x20   });\n\
         \x20   it(`${name} ansi black is not the background`, () => {\n\
         \x20     expect(mod.ANSI[0]).not.toBe(mod.RAMP.base00);\n\
         \x20   });\n\
         \x20 }\n\
         });\n",
    );
    s
}

fn py_test() -> String {
    let mut s = String::from(
        "# Generated by pente-forge (python conformance) — DO NOT EDIT\n\
         #\n\
         # Compares this language's constants against corpus.json, emitted from the\n\
         # Rust reference. Different code paths, so an emitter bug is detectable.\n\n\
         import json\n\
         import pathlib\n\
         import importlib\n\
         import pytest\n\n\
         CORPUS = json.loads((pathlib.Path(__file__).parent / \"corpus.json\").read_text())\n\n\
         \n@pytest.mark.parametrize(\"name\", sorted(CORPUS[\"themes\"]))\n\
         def test_ramp_matches_corpus(name):\n\
         \x20   mod = importlib.import_module(name)\n\
         \x20   expected = CORPUS[\"themes\"][name][\"ramp\"]\n\
         \x20   assert len(mod.RAMP) == 16\n\
         \x20   for slot, hexv in expected.items():\n\
         \x20       assert mod.RAMP[slot] == f\"#{hexv}\"\n\n\
         \n@pytest.mark.parametrize(\"name\", sorted(CORPUS[\"themes\"]))\n\
         def test_ansi_matches_corpus(name):\n\
         \x20   mod = importlib.import_module(name)\n\
         \x20   expected = CORPUS[\"themes\"][name][\"ansi\"]\n\
         \x20   assert len(mod.ANSI) == 16\n\
         \x20   for i, entry in enumerate(expected):\n\
         \x20       assert mod.ANSI[i] == f\"#{entry['hex']}\"\n\n\
         \n@pytest.mark.parametrize(\"name\", sorted(CORPUS[\"themes\"]))\n\
         def test_roles_match_corpus(name):\n\
         \x20   mod = importlib.import_module(name)\n\
         \x20   for role, hexv in CORPUS[\"themes\"][name][\"roles\"].items():\n\
         \x20       assert mod.ROLES[role] == f\"#{hexv}\"\n\n\
         \n@pytest.mark.parametrize(\"name\", sorted(CORPUS[\"themes\"]))\n\
         def test_ansi_black_is_not_the_background(name):\n\
         \x20   mod = importlib.import_module(name)\n\
         \x20   assert mod.ANSI[0] != mod.RAMP[\"base00\"]\n",
    );
    s.push('\n');
    s
}

fn go_test() -> String {
    let mut s = String::from(
        "// Generated by pente-forge (go conformance) — DO NOT EDIT\n\
         //\n\
         // Compares this package's constants against corpus.json, emitted from the\n\
         // Rust reference. Different code paths, so an emitter bug is detectable.\n\n\
         package pente\n\n\
         import (\n\
         \t\"encoding/json\"\n\
         \t\"os\"\n\
         \t\"testing\"\n\
         )\n\n\
         type corpusEntry struct {\n\
         \tRamp  map[string]string `json:\"ramp\"`\n\
         \tAnsi  []struct {\n\
         \t\tName string `json:\"name\"`\n\
         \t\tHex  string `json:\"hex\"`\n\
         \t} `json:\"ansi\"`\n\
         \tRoles map[string]string `json:\"roles\"`\n\
         }\n\n\
         type corpusFile struct {\n\
         \tThemes map[string]corpusEntry `json:\"themes\"`\n\
         }\n\n\
         func loadCorpus(t *testing.T) corpusFile {\n\
         \tt.Helper()\n\
         \tb, err := os.ReadFile(\"corpus.json\")\n\
         \tif err != nil {\n\t\tt.Fatalf(\"corpus.json: %v\", err)\n\t}\n\
         \tvar c corpusFile\n\
         \tif err := json.Unmarshal(b, &c); err != nil {\n\t\tt.Fatalf(\"corpus.json: %v\", err)\n\t}\n\
         \treturn c\n\
         }\n\n\
         var ramps = map[string]map[string]string{\n",
    );
    for theme in FleetTheme::ALL {
        let cap = cap_first(theme.slug());
        let _ = writeln!(s, "\t\"{}\": Ramp{cap},", theme.slug());
    }
    s.push_str("}\n\nvar ansis = map[string][]string{\n");
    for theme in FleetTheme::ALL {
        let cap = cap_first(theme.slug());
        let _ = writeln!(s, "\t\"{}\": Ansi{cap},", theme.slug());
    }
    s.push_str("}\n\nvar roles = map[string]map[string]string{\n");
    for theme in FleetTheme::ALL {
        let cap = cap_first(theme.slug());
        let _ = writeln!(s, "\t\"{}\": Roles{cap},", theme.slug());
    }
    s.push_str(
        "}\n\n\
         func TestConformance(t *testing.T) {\n\
         \tc := loadCorpus(t)\n\
         \tif len(c.Themes) == 0 {\n\t\tt.Fatal(\"corpus is empty\")\n\t}\n\
         \tfor name, want := range c.Themes {\n\
         \t\tramp, ok := ramps[name]\n\
         \t\tif !ok {\n\t\t\tt.Fatalf(\"%s: no generated ramp\", name)\n\t\t}\n\
         \t\tif len(ramp) != 16 {\n\t\t\tt.Errorf(\"%s: ramp has %d slots, want 16\", name, len(ramp))\n\t\t}\n\
         \t\tfor slot, hex := range want.Ramp {\n\
         \t\t\tif got := ramp[slot]; got != \"#\"+hex {\n\
         \t\t\t\tt.Errorf(\"%s ramp[%s] = %s, want #%s\", name, slot, got, hex)\n\t\t\t}\n\t\t}\n\
         \t\tansi := ansis[name]\n\
         \t\tif len(ansi) != 16 {\n\t\t\tt.Errorf(\"%s: ansi has %d entries, want 16\", name, len(ansi))\n\t\t}\n\
         \t\tfor i, e := range want.Ansi {\n\
         \t\t\tif got := ansi[i]; got != \"#\"+e.Hex {\n\
         \t\t\t\tt.Errorf(\"%s ansi[%d] = %s, want #%s\", name, i, got, e.Hex)\n\t\t\t}\n\t\t}\n\
         \t\tfor role, hex := range want.Roles {\n\
         \t\t\tif got := roles[name][role]; got != \"#\"+hex {\n\
         \t\t\t\tt.Errorf(\"%s roles[%s] = %s, want #%s\", name, role, got, hex)\n\t\t\t}\n\t\t}\n\
         \t\tif ansi[0] == ramp[\"base00\"] {\n\
         \t\t\tt.Errorf(\"%s: ansi black equals the background\", name)\n\t\t}\n\
         \t}\n\
         }\n",
    );
    s
}

fn cap_first(s: &str) -> String {
    let mut c = s.chars();
    c.next()
        .map_or_else(String::new, |f| f.to_uppercase().collect::<String>() + c.as_str())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_language_emits_every_theme_nonempty() {
        for lang in Lang::ALL {
            for theme in FleetTheme::ALL {
                let t = theme.load().unwrap();
                let m = lang.render_module(theme, &t);
                assert!(!m.trim().is_empty(), "{lang:?}/{theme:?} empty");
                assert!(m.contains("DO NOT EDIT"), "{lang:?}/{theme:?} lost provenance");
            }
            assert!(!lang.render_test().trim().is_empty());
        }
    }

    /// ★ The corpus is what makes the generated tests non-tautological, so it
    /// must actually contain every theme and every value.
    #[test]
    fn the_corpus_covers_every_theme_and_every_slot() {
        let c = corpus();
        for theme in FleetTheme::ALL {
            assert!(c.contains(&format!("\"{}\": {{", theme.slug())), "missing {theme:?}");
        }
        for slot in [
            "base00", "base01", "base02", "base03", "base04", "base05", "base06", "base07",
            "base08", "base09", "base0a", "base0b", "base0c", "base0d", "base0e", "base0f",
        ] {
            assert!(c.contains(&format!("\"{slot}\"")), "corpus missing {slot}");
        }
        for name in ANSI_NAMES {
            assert!(c.contains(&format!("\"{name}\"")), "corpus missing ansi {name}");
        }
    }

    /// The corpus must be valid JSON. Emitted by hand, so this is not free.
    #[test]
    fn the_corpus_is_well_formed_json() {
        let c = corpus();
        // Balance check over a document whose strings contain no braces or
        // brackets by construction (hex and identifiers only).
        let braces = c.chars().filter(|&x| x == '{').count() as i64
            - c.chars().filter(|&x| x == '}').count() as i64;
        let brackets = c.chars().filter(|&x| x == '[').count() as i64
            - c.chars().filter(|&x| x == ']').count() as i64;
        assert_eq!(braces, 0, "unbalanced braces");
        assert_eq!(brackets, 0, "unbalanced brackets");
        assert!(!c.contains(",\n  }"), "trailing comma before a close");
        assert!(!c.contains(",\n      }"), "trailing comma before a close");
        assert!(!c.contains(",\n      ]"), "trailing comma before a close");
    }

    /// Each language's constants must agree with the corpus — the same check
    /// the generated tests perform, run here so a mismatch fails the Rust build
    /// rather than waiting for three foreign toolchains.
    #[test]
    fn every_language_module_agrees_with_the_corpus() {
        for theme in FleetTheme::ALL {
            let t = theme.load().unwrap();
            let expected: Vec<String> = ramp_slots(&t)
                .into_iter()
                .map(|(_, c)| format!("#{}", c.to_bare_hex()))
                .collect();
            for lang in Lang::ALL {
                let m = lang.render_module(theme, &t);
                for hexv in &expected {
                    assert!(
                        m.contains(hexv.as_str()),
                        "{lang:?}/{theme:?} is missing {hexv}"
                    );
                }
            }
        }
    }

    #[test]
    fn generated_go_identifiers_are_exported_and_distinct() {
        let go = Lang::Go.render_test();
        for theme in FleetTheme::ALL {
            let cap = cap_first(theme.slug());
            assert!(go.contains(&format!("Ramp{cap}")), "missing Ramp{cap}");
            assert!(go.contains(&format!("Ansi{cap}")), "missing Ansi{cap}");
        }
    }
}
