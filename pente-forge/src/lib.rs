//! `pente-forge` — renders an authored theme to every consumer's native shape.
//!
//! The catalog is the source; everything here is a projection of it. A renderer
//! may not hold a colour, may not derive its own ANSI table, and may not
//! `format!()` its target's syntax.
//!
//! ## Why the target list is shaped the way it is
//!
//! The census found consumers in eight distinct colour encodings, and a
//! `#RRGGBB` grep sees three. Each target below exists because some real
//! consumer reads that exact shape today:
//!
//! | target | replaces |
//! |---|---|
//! | [`Target::NixBase16`] | `ishou/rendered/stylix-base16-*.nix`, `nix/lib/nord.nix` |
//! | [`Target::RustConsts`] | `irodzuki`'s bare-hex `NORD_BASE16`, `irodori::NORD` |
//! | [`Target::AnsiEscapes`] | `skim-tab`'s decimal `\x1b[38;2;…m` table |
//! | [`Target::GhosttyConf`] | `blackmatter-ghostty`'s own Nord generator |
//! | [`Target::Css`] | the Nord CSS vars hand-copied into a Flux HelmRelease |
//!
//! ## Generation zero
//!
//! [`Target::render`] is total over [`Target::ALL`] × every theme. That
//! totality is the property the census showed was missing: ishou had twelve
//! render targets for Nord and four for Vellum, so selecting a non-default
//! theme silently un-themed eight consumers. Here a target that cannot render a
//! theme does not compile.

pub mod nix_ast;
pub mod reconcile;

use nix_ast::{NixExpr, NixFile};
use pente_spec::{FleetTheme, Srgb8, Theme, Token};

/// Every consumer shape a theme is projected into.
///
/// Closed, and `ALL` is what the differential iterates — so adding a target
/// without teaching every theme to render it is a compile error, not a blank
/// artifact discovered later.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Target {
    /// An already-parsed Nix attrset. **Never** `{ yaml = <drv>; }` — that form
    /// makes stylix `readFile` a derivation mid-evaluation, and since the
    /// derivation is per-system that build is Linux, which leaves every NixOS
    /// node unevaluable from a Mac.
    NixBase16,
    /// Rust constants, for consumers that link rather than read a file.
    RustConsts,
    /// Truecolor SGR escapes, decimal — the encoding a `#RRGGBB` grep is blind
    /// to and which `skim-tab` carries by hand today.
    AnsiEscapes,
    /// ghostty's `key = value` config.
    GhosttyConf,
    /// CSS custom properties.
    Css,
}

impl Target {
    pub const ALL: [Self; 5] = [
        Self::NixBase16,
        Self::RustConsts,
        Self::AnsiEscapes,
        Self::GhosttyConf,
        Self::Css,
    ];

    /// The artifact's filename for a given theme.
    #[must_use]
    pub fn file_name(self, theme: FleetTheme) -> String {
        let slug = theme.slug();
        match self {
            Self::NixBase16 => format!("base16-{slug}.nix"),
            Self::RustConsts => format!("{slug}.rs"),
            Self::AnsiEscapes => format!("{slug}.ansi"),
            Self::GhosttyConf => format!("{slug}.ghostty"),
            Self::Css => format!("{slug}.css"),
        }
    }

    /// Render this theme into this target. Total by construction.
    #[must_use]
    pub fn render(self, theme: FleetTheme, t: &Theme) -> String {
        match self {
            Self::NixBase16 => render_nix_base16(theme, t),
            Self::RustConsts => render_rust(theme, t),
            Self::AnsiEscapes => render_ansi(t),
            Self::GhosttyConf => render_ghostty(t),
            Self::Css => render_css(t),
        }
    }
}

/// The sixteen ramp slots, in wire order, as `(name, value)`.
fn ramp_slots(t: &Theme) -> [(&'static str, Srgb8); 16] {
    let r = &t.ramp;
    [
        ("base00", r.base00),
        ("base01", r.base01),
        ("base02", r.base02),
        ("base03", r.base03),
        ("base04", r.base04),
        ("base05", r.base05),
        ("base06", r.base06),
        ("base07", r.base07),
        ("base08", r.base08),
        ("base09", r.base09),
        ("base0a", r.base0a),
        ("base0b", r.base0b),
        ("base0c", r.base0c),
        ("base0d", r.base0d),
        ("base0e", r.base0e),
        ("base0f", r.base0f),
    ]
}

/// The ANSI-16 names in index order — the same order `Ansi16::in_order` yields.
const ANSI_NAMES: [&str; 16] = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "bright-black",
    "bright-red",
    "bright-green",
    "bright-yellow",
    "bright-blue",
    "bright-magenta",
    "bright-cyan",
    "bright-white",
];

fn provenance(theme: FleetTheme, target: &str) -> Vec<String> {
    vec![
        format!("Generated by pente-forge ({target}) — DO NOT EDIT"),
        format!("Source of truth: pente/themes/{}.theme.lisp", theme.slug()),
        String::new(),
        "Regenerate:  pente-forge build".to_string(),
        "Verify:      pente-forge check   (fails on any drift)".to_string(),
    ]
}

fn render_nix_base16(theme: FleetTheme, t: &Theme) -> String {
    let mut entries = vec![
        ("system".to_string(), NixExpr::Str("base16".into())),
        ("name".to_string(), NixExpr::Str(t.title.clone())),
        ("author".to_string(), NixExpr::Str(t.author.clone())),
        // Derived, never authored — stylix interpolates both into artefact
        // NAMES, so a defaulted "untitled"/"unspecified" keeps every colour
        // byte-identical while renaming a pile of store paths.
        ("variant".to_string(), NixExpr::Str("dark".into())),
        ("slug".to_string(), NixExpr::Str(theme.slug().into())),
    ];
    for (k, v) in ramp_slots(t) {
        entries.push((k.to_string(), NixExpr::Str(v.to_bare_hex())));
    }
    let mut header = provenance(theme, "nix-base16");
    header.push(String::new());
    header.push("An ALREADY-PARSED attrset. Consumed as:".into());
    header.push(format!(
        "  stylix.base16Scheme = import ./base16-{}.nix;",
        theme.slug()
    ));
    header.push(String::new());
    header.push("NOT `{ yaml = <derivation>; }` — that form makes stylix readFile a".into());
    header.push("derivation, which is an IFD, which forces a per-system (Linux) build".into());
    header.push("during evaluation and leaves every NixOS node unevaluable from a Mac.".into());
    NixFile::new(header, NixExpr::AttrSet(entries)).render()
}

fn render_rust(theme: FleetTheme, t: &Theme) -> String {
    use std::fmt::Write as _;
    let mut out = String::new();
    for line in provenance(theme, "rust-consts") {
        if line.is_empty() {
            out.push_str("//\n");
        } else {
            let _ = writeln!(out, "// {line}");
        }
    }
    // An item-level attribute, NOT an inner `#![…]`: these files are consumed
    // with `include!`, and an inner attribute is only legal at the top of a
    // file or module. Emitting one would make every generated artifact
    // uncompilable in the way its consumers actually use it.
    out.push('\n');
    let _ = writeln!(
        out,
        "/// The sixteen base16 slots, in wire order, as `0xRRGGBB`."
    );
    let _ = writeln!(out, "#[allow(clippy::unreadable_literal)]");
    let _ = writeln!(out, "pub const BASE16: [u32; 16] = [");
    for (name, c) in ramp_slots(t) {
        let _ = writeln!(
            out,
            "    0x{:02X}{:02X}{:02X}, // {name}",
            c.r, c.g, c.b
        );
    }
    let _ = writeln!(out, "];\n");
    let _ = writeln!(
        out,
        "/// The ANSI-16 table — AUTHORED, never derived. Four independent"
    );
    let _ = writeln!(
        out,
        "/// derivations of this disagreed before it had one source."
    );
    let _ = writeln!(out, "#[allow(clippy::unreadable_literal)]");
    let _ = writeln!(out, "pub const ANSI16: [u32; 16] = [");
    for (i, tok) in t.ansi.in_order().into_iter().enumerate() {
        let c = t.resolve(tok);
        let _ = writeln!(
            out,
            "    0x{:02X}{:02X}{:02X}, // {}",
            c.r, c.g, c.b, ANSI_NAMES[i]
        );
    }
    let _ = writeln!(out, "];");
    out
}

fn render_ansi(t: &Theme) -> String {
    use std::fmt::Write as _;
    let mut out = String::new();
    // Decimal truecolor SGR — the encoding a `#RRGGBB` grep cannot see, which
    // is why skim-tab's copy of this went unnoticed.
    for (i, tok) in t.ansi.in_order().into_iter().enumerate() {
        let c = t.resolve(tok);
        let _ = writeln!(
            out,
            "{}\t\\x1b[38;2;{};{};{}m",
            ANSI_NAMES[i], c.r, c.g, c.b
        );
    }
    out
}

fn render_ghostty(t: &Theme) -> String {
    use std::fmt::Write as _;
    let mut out = String::new();
    for (i, tok) in t.ansi.in_order().into_iter().enumerate() {
        let _ = writeln!(out, "palette = {i}={}", hash_hex(t.resolve(tok)));
    }
    let _ = writeln!(out, "background = {}", hash_hex(t.resolve(t.roles.background)));
    let _ = writeln!(out, "foreground = {}", hash_hex(t.resolve(t.roles.text)));
    let _ = writeln!(
        out,
        "cursor-color = {}",
        hash_hex(t.resolve(t.roles.cursor))
    );
    let _ = writeln!(
        out,
        "selection-background = {}",
        hash_hex(t.resolve(t.roles.selection))
    );
    out
}

fn render_css(t: &Theme) -> String {
    use std::fmt::Write as _;
    let mut out = String::new();
    let _ = writeln!(out, "/* {} */", t.title);
    let _ = writeln!(out, ":root {{");
    for (name, c) in ramp_slots(t) {
        let _ = writeln!(out, "  --{name}: {};", hash_hex(c));
    }
    for (name, tok) in roles_named(t) {
        let _ = writeln!(out, "  --{name}: {};", hash_hex(t.resolve(tok)));
    }
    let _ = writeln!(out, "}}");
    out
}

fn hash_hex(c: Srgb8) -> String {
    format!("#{}", c.to_bare_hex())
}

/// Roles as `(css-name, token)`.
fn roles_named(t: &Theme) -> [(&'static str, Token); 16] {
    let r = &t.roles;
    [
        ("background", r.background),
        ("surface", r.surface),
        ("surface-elevated", r.surface_elevated),
        ("text", r.text),
        ("text-muted", r.text_muted),
        ("text-dim", r.text_dim),
        ("primary", r.primary),
        ("accent", r.accent),
        ("border", r.border),
        ("error", r.error),
        ("warning", r.warning),
        ("success", r.success),
        ("info", r.info),
        ("selection", r.selection),
        ("cursor", r.cursor),
        ("agent", r.agent),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn all_pairs() -> Vec<(FleetTheme, Target, String)> {
        let mut v = Vec::new();
        for th in FleetTheme::ALL {
            let t = th.load().expect("theme compiles");
            for tg in Target::ALL {
                v.push((th, tg, tg.render(th, &t)));
            }
        }
        v
    }

    /// ★ Totality. Every target renders every theme.
    ///
    /// This is the asymmetry the census measured and this crate exists to
    /// remove: ishou had twelve render targets for Nord and four for Vellum, so
    /// choosing a non-default theme silently un-themed eight consumers.
    #[test]
    fn every_target_renders_every_theme_nonempty() {
        let pairs = all_pairs();
        assert_eq!(pairs.len(), FleetTheme::ALL.len() * Target::ALL.len());
        for (th, tg, out) in pairs {
            assert!(!out.trim().is_empty(), "{th:?}/{tg:?} rendered nothing");
        }
    }

    #[test]
    fn rendering_is_deterministic() {
        for (th, tg, out) in all_pairs() {
            let again = tg.render(th, &th.load().unwrap());
            assert_eq!(out, again, "{th:?}/{tg:?} is not deterministic");
        }
    }

    /// No two themes may render the same bytes for the same target — the
    /// name-pointing-at-another-palette bug, caught at the artifact layer.
    #[test]
    fn no_two_themes_render_identically() {
        for tg in Target::ALL {
            for (i, a) in FleetTheme::ALL.iter().enumerate() {
                for b in FleetTheme::ALL.iter().skip(i + 1) {
                    let ra = tg.render(*a, &a.load().unwrap());
                    let rb = tg.render(*b, &b.load().unwrap());
                    assert_ne!(ra, rb, "{tg:?}: {a:?} and {b:?} render identically");
                }
            }
        }
    }

    /// The Nix target must never reintroduce the IFD shape.
    #[test]
    fn the_nix_target_emits_a_parsed_attrset_not_a_yaml_derivation() {
        for th in FleetTheme::ALL {
            let out = Target::NixBase16.render(th, &th.load().unwrap());
            let code: String = out
                .lines()
                .filter(|l| !l.trim_start().starts_with('#'))
                .collect::<Vec<_>>()
                .join("\n");
            assert!(!code.contains("yaml ="), "{th:?} reintroduced the IFD shape");
            assert!(code.contains("base00 = \""), "{th:?} is not a parsed attrset");
            // Metadata is load-bearing: absent, stylix defaults it and renames
            // a pile of store paths while keeping every colour identical.
            for k in ["system", "name", "author", "variant", "slug"] {
                assert!(code.contains(k), "{th:?} dropped {k}");
            }
        }
    }

    /// Nord's Nix render must match what the fleet already ships, so adopting
    /// pente-forge repaints nothing.
    #[test]
    fn nord_nix_matches_the_fleet_bytes() {
        let out = Target::NixBase16.render(FleetTheme::Nord, &FleetTheme::Nord.load().unwrap());
        for (slot, want) in [
            ("base00", "2e3440"),
            ("base0c", "88c0d0"),
            ("base0f", "5e81ac"),
        ] {
            assert!(
                out.contains(&format!("{slot} = \"{want}\";")),
                "missing {slot} = {want}"
            );
        }
    }

    /// The ANSI target carries DECIMAL escapes — the encoding a `#RRGGBB` grep
    /// cannot see, and the reason skim-tab's hand-copy went unnoticed.
    #[test]
    fn the_ansi_target_emits_decimal_truecolor() {
        let out = Target::AnsiEscapes.render(FleetTheme::Nord, &FleetTheme::Nord.load().unwrap());
        assert!(out.contains("\\x1b[38;2;59;66;82m"), "black should be 3b4252:\n{out}");
        assert!(!out.contains('#'), "the ANSI target must not emit hex");
    }

    #[test]
    fn file_names_are_distinct_across_the_whole_matrix() {
        let mut seen = std::collections::HashSet::new();
        for th in FleetTheme::ALL {
            for tg in Target::ALL {
                assert!(seen.insert(tg.file_name(th)), "duplicate file name");
            }
        }
        assert_eq!(seen.len(), FleetTheme::ALL.len() * Target::ALL.len());
    }
}
